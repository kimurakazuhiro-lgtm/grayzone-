-- 研修結果画面で使う、安全な集計用の設定です。
-- 個人ごとの回答・自由記述・事業種は返しません。

-- 以前の集計関数を、5Keys の集計を返す新しい形に置き換えます。
drop function if exists public.question_results();

create function public.question_results()
returns table (
  question_number integer,
  category text,
  question_text text,
  entered_count bigint,
  not_entered_count bigint,
  response_count bigint,
  five_keys jsonb
)
language sql
security definer
set search_path = public
as $$
  with response_items as (
    select
      (question.ordinality - 1)::integer as question_number,
      question.item ->> 'category' as category,
      question.item ->> 'text' as question_text,
      response.answers -> 'answers' ->> (question.ordinality - 1)::text as answer,
      response.answers -> 'responseKeys' -> (question.ordinality - 1)::text as response_keys
    from public.responses as response
    cross join lateral jsonb_array_elements(response.answers -> 'questions')
      with ordinality as question(item, ordinality)
  ),
  answer_summary as (
    select
      min(question_number)::integer as question_number,
      category,
      question_text,
      count(*) filter (where answer = '入る')::bigint as entered_count,
      count(*) filter (where answer = '入らない')::bigint as not_entered_count,
      count(*)::bigint as response_count
    from response_items
    where answer in ('入る', '入らない')
    group by category, question_text
  ),
  key_counts as (
    select
      category,
      question_text,
      selected_key.key_name,
      count(*)::bigint as key_count
    from response_items
    cross join lateral jsonb_array_elements_text(
      coalesce(response_keys, '[]'::jsonb)
    ) as selected_key(key_name)
    where answer = '入る'
    group by category, question_text, selected_key.key_name
  ),
  key_summary as (
    select
      category,
      question_text,
      jsonb_object_agg(key_name, key_count) as five_keys
    from key_counts
    group by category, question_text
  )
  select
    answer_summary.question_number,
    answer_summary.category,
    answer_summary.question_text,
    answer_summary.entered_count,
    answer_summary.not_entered_count,
    answer_summary.response_count,
    coalesce(key_summary.five_keys, '{}'::jsonb) as five_keys
  from answer_summary
  left join key_summary
    on key_summary.category = answer_summary.category
    and key_summary.question_text = answer_summary.question_text
  order by answer_summary.category, answer_summary.question_text;
$$;

revoke all on function public.question_results() from public;
grant execute on function public.question_results() to anon, authenticated;

-- グループ演習で入力した「気づき」と「改善案」を保存するテーブルです。
-- 読み取り用の公開ポリシーは作らないため、参加者同士で自由記述は見えません。
create table if not exists public.workshop_notes (
  id bigint generated by default as identity primary key,
  category text not null,
  question_text text not null,
  insights text not null default '',
  improvements text not null default '',
  created_at timestamptz not null default now()
);

alter table public.workshop_notes enable row level security;

drop policy if exists "Allow public insert workshop notes" on public.workshop_notes;
create policy "Allow public insert workshop notes"
on public.workshop_notes
for insert
to anon, authenticated
with check (true);
